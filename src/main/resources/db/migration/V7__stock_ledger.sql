-- Stock ledger (warehouse-service 1.6.0): warehouse-service owns stock quantities and
-- movements; the backend keeps products.stock_quantity as a projection that this
-- service pushes through stock_level_outbox (see INVENTORY_OWNERSHIP_CONTRACT.md).
--
-- Product ids come from the backend catalog; there is no product table here.
-- ledger_version is a per-product counter incremented on every ledger change; the
-- backend applies a pushed level only when its version is newer than the stored one.

CREATE TABLE stock_items (
    product_id bigint PRIMARY KEY,
    quantity integer NOT NULL CHECK (quantity >= 0),
    ledger_version bigint NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL
);

-- Movement ids imported from the backend's inventory_movements are kept; the identity
-- is moved past the largest imported id afterwards (StockImporter).
CREATE TABLE stock_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES stock_items(product_id) ON DELETE CASCADE,
    order_id bigint,
    reservation_id uuid,
    type varchar(32) NOT NULL CHECK (type IN ('INITIAL_STOCK', 'ADMIN_ADJUSTMENT', 'ORDER_DEDUCTED',
        'ORDER_RESTORED', 'PURCHASE_RECEIVED', 'RETURN_RESTOCKED')),
    delta integer NOT NULL,
    quantity_after integer NOT NULL,
    actor varchar(255) NOT NULL,
    reason varchar(500) NOT NULL,
    request_id uuid,
    -- The item's ledger_version after this movement; null for imported movements.
    ledger_version bigint,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_stock_movements_product_request UNIQUE (product_id, request_id)
);
CREATE INDEX idx_stock_movements_product_created ON stock_movements(product_id, created_at);
CREATE INDEX idx_stock_movements_order ON stock_movements(order_id);
CREATE INDEX idx_stock_movements_reservation ON stock_movements(reservation_id);

-- One reservation per checkout: PENDING_CONFIRMATION until the backend confirms it with
-- the order id, RELEASED when the backend compensates or the reaper expires it.
CREATE TABLE stock_reservations (
    reservation_id uuid PRIMARY KEY,
    username varchar(255) NOT NULL,
    status varchar(32) NOT NULL CHECK (status IN ('PENDING_CONFIRMATION', 'CONFIRMED', 'RELEASED')),
    order_id bigint,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    correlation_id varchar(128),
    traceparent varchar(55)
);
CREATE INDEX idx_stock_reservations_status_created ON stock_reservations(status, created_at);

-- The reserved lines with the quantity and ledger version they left, so a repeated
-- reserve call returns the stored body.
CREATE TABLE stock_reservation_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id uuid NOT NULL REFERENCES stock_reservations(reservation_id) ON DELETE CASCADE,
    product_id bigint NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    quantity_after integer NOT NULL,
    ledger_version bigint NOT NULL,
    CONSTRAINT uk_stock_reservation_lines_product UNIQUE (reservation_id, product_id)
);
CREATE INDEX idx_stock_reservation_lines_product ON stock_reservation_lines(product_id);

-- Restores after order.cancelled: at most one per order (the feed's processed_events
-- covers replays of one event; this covers two events for one order).
CREATE TABLE stock_restores (
    order_id bigint PRIMARY KEY,
    event_id uuid NOT NULL,
    restored_at timestamp(6) NOT NULL
);

-- Stock levels waiting to be pushed to the backend projection
-- (POST /internal/v1/inventory/levels); rows are deleted once the backend accepted them.
CREATE TABLE stock_level_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    quantity integer NOT NULL,
    ledger_version bigint NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    last_error varchar(500),
    created_at timestamp(6) NOT NULL,
    correlation_id varchar(128),
    traceparent varchar(55)
);
CREATE INDEX idx_stock_level_outbox_product ON stock_level_outbox(product_id);
