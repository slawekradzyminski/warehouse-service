-- Customer notifications are written to an outbox in the same transaction as
-- the shipment or return change and sent to the backend afterwards, with
-- retries; request_id lets the backend drop duplicates.
CREATE TABLE notification_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL,
    username varchar(255) NOT NULL,
    template varchar(32) NOT NULL CHECK (template IN ('ORDER_SHIPPED', 'ORDER_DELIVERED', 'RETURN_UPDATED')),
    properties varchar(4000) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamp(6) NOT NULL,
    sent_at timestamp(6),
    last_error varchar(500),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_notification_outbox_request UNIQUE (request_id)
);
CREATE INDEX idx_notification_outbox_due ON notification_outbox(sent_at, next_attempt_at);

-- One row per order that ever had a return request. Return requests lock the
-- row (SELECT ... FOR UPDATE) so concurrent requests for the same order are
-- serialised across every warehouse-service instance.
CREATE TABLE order_locks (
    order_id bigint PRIMARY KEY
);
