-- Shipment tracking with a simulated carrier. A shipment handed over without a
-- tracking number is "simulated": the service generates the tracking number and
-- a scheduler advances it through the carrier statuses. Every shipped shipment
-- (simulated or manual) records its tracking timeline in tracking_events.

ALTER TABLE shipments ADD COLUMN simulated boolean NOT NULL DEFAULT false;
CREATE INDEX idx_shipments_tracking_number ON shipments(tracking_number);
CREATE INDEX idx_shipments_simulated_status ON shipments(simulated, status);

CREATE TABLE tracking_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id bigint NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
    status varchar(24) NOT NULL CHECK (status IN (
        'LABEL_CREATED', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERY_FAILED', 'DELIVERED')),
    location varchar(120) NOT NULL,
    description varchar(255) NOT NULL,
    occurred_at timestamp(6) NOT NULL
);
CREATE INDEX idx_tracking_events_shipment ON tracking_events(shipment_id, occurred_at);

