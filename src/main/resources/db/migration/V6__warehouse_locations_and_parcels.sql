ALTER TABLE shipments ALTER COLUMN location_code SET NOT NULL;
ALTER TABLE shipments ADD CONSTRAINT fk_shipments_location
    FOREIGN KEY (location_code) REFERENCES warehouse_locations(code);
ALTER TABLE shipments ADD COLUMN lines_pending boolean NOT NULL DEFAULT false;
UPDATE shipments SET lines_pending = true;
ALTER TABLE shipments DROP CONSTRAINT uk_shipments_order;
ALTER TABLE shipments ADD CONSTRAINT uk_shipments_order_location UNIQUE (order_id, location_code);
CREATE INDEX idx_shipments_lines_pending ON shipments(lines_pending);

CREATE TABLE shipment_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id bigint NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
    product_id bigint NOT NULL,
    product_name varchar(255) NOT NULL,
    category varchar(255),
    quantity integer NOT NULL CHECK (quantity > 0),
    CONSTRAINT uk_shipment_lines_product UNIQUE (shipment_id, product_id)
);

-- order_locks now serialises every fulfilment write of an order (not only returns) and
-- remembers the fulfilment state last mirrored to the backend. Every existing shipment
-- gets its lock row; before 1.5.0 the shipment status was mirrored one to one.
ALTER TABLE order_locks ADD COLUMN mirrored_state varchar(16) CHECK (mirrored_state IN (
    'NONE', 'AWAITING_PICK', 'PICKED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED'));
INSERT INTO order_locks (order_id)
    SELECT DISTINCT s.order_id FROM shipments s
    WHERE NOT EXISTS (SELECT 1 FROM order_locks l WHERE l.order_id = s.order_id);
UPDATE order_locks SET mirrored_state = (
    SELECT s.status FROM shipments s WHERE s.order_id = order_locks.order_id);
