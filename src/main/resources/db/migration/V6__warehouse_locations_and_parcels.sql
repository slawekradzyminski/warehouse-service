-- Multiple warehouse locations and split shipments (warehouse-service 1.5.0).
--
-- A product is stocked by category: location_products maps a category to the
-- locations that ship it, as PRIMARY or BACKUP. The category '*' matches every
-- category that has no row of its own at that location, so categories created
-- later in the backend are still stocked. Release allocates each order line to
-- a location and writes one shipment (parcel) per location with its lines.
--
-- The backend still sees one fulfilment state per order: order_locks.mirrored_state
-- remembers the last state mirrored to it (forward-only, see FulfilmentAggregate).

CREATE TABLE warehouse_locations (
    code varchar(8) PRIMARY KEY,
    name varchar(120) NOT NULL,
    city varchar(120) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    priority integer NOT NULL CHECK (priority > 0)
);
INSERT INTO warehouse_locations (code, name, city, active, priority) VALUES
    ('KRK', 'Krakow Central', 'Krakow', true, 1),
    ('GDN', 'Gdansk North', 'Gdansk', true, 2);

CREATE TABLE location_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code varchar(8) NOT NULL REFERENCES warehouse_locations(code),
    category varchar(255) NOT NULL,
    role varchar(16) NOT NULL CHECK (role IN ('PRIMARY', 'BACKUP')),
    CONSTRAINT uk_location_products_category UNIQUE (location_code, category)
);
-- Baseline: Krakow ships everything, Gdansk backs it up. The demo profile adds the
-- per-category split (DemoDataSeeder), so a mixed cart is shipped from both.
