-- Warehouse fulfilment schema. Orders and products live in the backend, so
-- order_id and product_id are plain references without foreign keys; names
-- and prices are snapshots taken when the row was written.
-- Runs in the schema named by spring.flyway.schemas (warehouse).

CREATE TABLE shipments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    username varchar(255) NOT NULL,
    total_units integer NOT NULL CHECK (total_units >= 0),
    status varchar(16) NOT NULL CHECK (status IN (
        'AWAITING_PICK', 'PICKED', 'PACKED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    carrier varchar(16) CHECK (carrier IN ('INPOST', 'DPD', 'DHL', 'UPS')),
    tracking_number varchar(32),
    weight_kg numeric(5,2) CHECK (weight_kg > 0),
    created_by varchar(255) NOT NULL,
    last_actor varchar(255) NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    picked_at timestamp(6),
    packed_at timestamp(6),
    shipped_at timestamp(6),
    delivered_at timestamp(6),
    cancelled_at timestamp(6),
    CONSTRAINT uk_shipments_order UNIQUE (order_id)
);
CREATE INDEX idx_shipments_status_created ON shipments(status, created_at);

CREATE TABLE return_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    order_total_amount numeric(10,2) NOT NULL,
    order_subtotal_amount numeric(10,2),
    username varchar(255) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN (
        'REQUESTED', 'APPROVED', 'REJECTED', 'RECEIVED', 'REFUNDED')),
    reason varchar(32) NOT NULL CHECK (reason IN (
        'DAMAGED', 'WRONG_ITEM', 'NOT_AS_DESCRIBED', 'NO_LONGER_NEEDED')),
    customer_comment varchar(1000),
    resolution_note varchar(500),
    refund_amount numeric(10,2),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    approved_at timestamp(6),
    rejected_at timestamp(6),
    received_at timestamp(6),
    refunded_at timestamp(6)
);
CREATE INDEX idx_return_requests_order ON return_requests(order_id);
CREATE INDEX idx_return_requests_user ON return_requests(username, created_at);
CREATE INDEX idx_return_requests_status ON return_requests(status, created_at);

CREATE TABLE return_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id bigint NOT NULL REFERENCES return_requests(id) ON DELETE CASCADE,
    product_id bigint NOT NULL,
    product_name varchar(255) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL,
    item_condition varchar(16) CHECK (item_condition IN ('RESELLABLE', 'DAMAGED'))
);
CREATE INDEX idx_return_items_return ON return_items(return_id);
CREATE INDEX idx_return_items_product ON return_items(product_id);

CREATE TABLE suppliers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    email varchar(255) NOT NULL,
    lead_time_days integer NOT NULL CHECK (lead_time_days BETWEEN 0 AND 365),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_suppliers_name UNIQUE (name)
);

CREATE TABLE purchase_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES suppliers(id),
    status varchar(24) NOT NULL CHECK (status IN (
        'DRAFT', 'SUBMITTED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    note varchar(500),
    created_by varchar(255) NOT NULL,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    submitted_at timestamp(6),
    expected_at timestamp(6),
    received_at timestamp(6),
    cancelled_at timestamp(6)
);
CREATE INDEX idx_purchase_orders_status ON purchase_orders(status, created_at);

CREATE TABLE purchase_order_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id bigint NOT NULL,
    product_name varchar(255) NOT NULL,
    ordered_quantity integer NOT NULL CHECK (ordered_quantity > 0),
    received_quantity integer NOT NULL DEFAULT 0
        CHECK (received_quantity >= 0 AND received_quantity <= ordered_quantity),
    unit_cost numeric(10,2) NOT NULL CHECK (unit_cost > 0),
    CONSTRAINT uk_purchase_order_lines_product UNIQUE (purchase_order_id, product_id)
);
CREATE INDEX idx_purchase_order_lines_product ON purchase_order_lines(product_id);

CREATE TABLE purchase_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    request_id uuid NOT NULL,
    lines_fingerprint varchar(64) NOT NULL,
    received_by varchar(255) NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_purchase_receipts_request UNIQUE (purchase_order_id, request_id)
);
